"""Regenerates shared/prompts.mjs from shared/prompts.json.

shared/prompts.json is the single source of truth for the two model prompts. The browser imports the generated
.mjs (browsers can't portably import JSON) and the Python server reads the JSON directly, so both always send
identical instructions. A pytest checks the two files are in sync.

Run:  .venv\\Scripts\\python tools/sync_prompts.py
"""

from __future__ import annotations

import json
from pathlib import Path

SHARED = Path(__file__).resolve().parent.parent / "shared"


def render(prompts: dict) -> str:
    body = {k: v for k, v in prompts.items() if not k.startswith("_")}
    return (
        "// GENERATED by tools/sync_prompts.py from prompts.json. Do not edit by hand.\n"
        f"export default {json.dumps(body, indent=2, ensure_ascii=False)};\n"
    )


def main() -> None:
    prompts = json.loads((SHARED / "prompts.json").read_text(encoding="utf-8"))
    (SHARED / "prompts.mjs").write_text(render(prompts), encoding="utf-8")
    print("[sync_prompts] wrote shared/prompts.mjs")


if __name__ == "__main__":
    main()
